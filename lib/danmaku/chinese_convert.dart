/// 把繁体文本转成简体。
///
/// ## 语义
/// · 简体字**不在表里** ⇒ 原样返回 ⇒ **幂等**（转过的再转不变）
/// · 空串 / 纯 ASCII ⇒ 原样返回（快速短路，零查表开销）
///
/// ## 为什么幂等很重要
/// 客户端会对"服务端已转过的内容"再转一次（防御性），
/// 幂等保证那不会破坏数据。
String toSimplified(String input) {
  if (input.isEmpty) return input;
  var hasAny = false;
  for (var i = 0; i < input.length; i++) {
    if (t2sTable.containsKey(input[i])) {
      hasAny = true;
      break;
    }
  }
  if (!hasAny) return input;

  final sb = StringBuffer();
  for (var i = 0; i < input.length; i++) {
    final c = input[i];
    sb.write(t2sTable[c] ?? c);
  }
  return sb.toString();
}
