// 语言码 → 中文名映射 + 轨道名本地化。
//
// ## 为什么需要（用户要求）
// > "音频、字幕全部显示中字、音频为国语、粤语等，
// >  和字幕为简体中文、繁体中文、中英双语、简英特字/繁英特字/
// >  简体中字/繁體中字/英字"
//
// ## 问题：服务端与内核给的都是**英文**
// 真机实测（《复仇者联盟》）：
// · 服务端 `DisplayTitle`：`English TRUEHD 7.1 (默认)`、`Chinese (PGSSUB)`
// · mpv track-list `title`：`英语`、`国语`、`简英特字`、`繁體中字`
//
// ⇒ 服务端的名字**信息更全**（编码+声道）但是**英文**；
//    内核的名字**是中文**但缺编码信息。
//    最优解 = **两者合并**：中文语言名 + 服务端的编码/声道。
library;

/// 语言码/英文名 → 中文名。
///
/// ## 覆盖范围（按实测出现频率排序）
/// 1. Emby 的 `Language`（ISO 639-2/B）：`chi`/`eng`/`jpn`…
/// 2. Emby 的 `DisplayLanguage`（英文全名）：`Chinese`/`English`…
/// 3. mpv 的 `slang`（ISO 639-1 或 639-2）：`zh`/`en`/`chi`…
///
/// ⚠️ 找不到就**原样返回**（不猜、不乱翻）—— 宁可显示 `Twi` 也不假装是中文。
String? languageToChinese(String? code) {
  if (code == null) return null;
  final k = code.trim().toLowerCase();
  if (k.isEmpty) return null;
  return _langMap[k];
}

/// 把"语言 + 细节"合成中文标签。
///
/// [language] 原始语言码（可为 null）；[detail] 附加信息（编码/声道等，可为 null）。
/// 例：`('chi', 'TRUEHD 7.1')` → `国语 · TRUEHD 7.1`
String? chineseTrackLabel(String? language, String? detail) {
  final zh = languageToChinese(language);
  final d = detail?.trim();
  if (zh == null && (d == null || d.isEmpty)) return null;
  if (zh == null) return d;
  if (d == null || d.isEmpty) return zh;
  return '$zh · $d';
}

