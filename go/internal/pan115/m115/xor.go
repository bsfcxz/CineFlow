// xorClientKey 是固定的 12 字节客户端密钥（明文常量，非随机、非派生）。
// Encode 的最后一步与 Decode 的第一步（反转后）都用它，方向对称。
var xorClientKey = [12]byte{
	0x78, 0x06, 0xad, 0x4c, 0x33, 0x86, 0x5d, 0x18,
	0x4c, 0x01, 0x3f, 0x46,
}

// xorDeriveKey 从 seed 派生 size 字节密钥。
//
// 公式（逐字节取自上游）：
//
//	key[i] = ((seed[i] + xorKeySeed[size*i]) & 0xff) ^ xorKeySeed[size*(size-i-1)]
//
// size 是调用方硬编码的常量（本包只有 4 和 12 两个取值），不是由数据长度推导的。
// seed 至少要有 size 字节，否则会 panic。
func xorDeriveKey(seed []byte, size int) []byte {
	key := make([]byte, size)
	for i := 0; i < size; i++ {
		key[i] = (seed[i] + xorKeySeed[size*i]) & 0xff
		key[i] ^= xorKeySeed[size*(size-i-1)]
	}
	return key
}

// xorTransform 按上游的分段规则做 XOR：先处理 len(data)%4 个"余数字节"（与 key 从头对齐），
// 其余按每 4 字节一组、用 key[(i-mod)%keyLen] 逐字节异或。
//
// 该函数是自逆的（XOR 性质），故 Encode/Decode 两侧复用同一实现。
func xorTransform(data []byte, key []byte) {
	dataSize, keySize := len(data), len(key)
	mod := dataSize % 4
	if mod > 0 {
		for i := 0; i < mod; i++ {
			data[i] ^= key[i%keySize]
		}
	}
	for i := mod; i < dataSize; i++ {
		data[i] ^= key[(i-mod)%keySize]
	}
}
